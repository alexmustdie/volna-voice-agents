        "Не проговаривай списки и формулировки из инструкции дословно.",
        "Реакции соответствуют услышанному. Одобрение ('отлично', 'здорово', 'прекрасно') только в "
        "ответ "
        "на согласие. На отказ, сомнение или нейтральный ответ реагируй нейтрально: 'понятно', "
