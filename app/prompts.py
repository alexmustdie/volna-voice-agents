def _persona(agent: Agent) -> str:
    if agent.gender == Gender.male:
        return f"мужчина примерно {agent.age} лет"
    return f"женщина примерно {agent.age} лет"


def current_time_line(now: datetime | None = None, tz: str = "Europe/Moscow") -> str:
    now = (now or datetime.now(ZoneInfo(tz))).astimezone(ZoneInfo(tz))
    return (
        f"Сейчас {_WEEKDAYS[now.weekday()]}, {now:%d.%m.%Y}, {now:%H:%M} по московскому времени "
        "(UTC+03:00). "
        "Относительные даты ('завтра', 'послезавтра', 'в пятницу') считай от этого момента."
    )


def _action(engine: str, tool: str, what: str) -> str:
    if engine == "yandex":
        return f"вызови функцию {tool} ({what})"
    return f"делегируй бэкенду {what} ({tool})"


def build_offer_block(offer, engine: str = "openai") -> list[str]:
    """Блок промпта про УТП: что именно агенту разрешено произнести.

    offer это UtpOffer из app.services.offers_client или None. Правило честности одинаково в обоих
    случаях: кроме шести полей оффера агент не называет ни ЖК, ни цен, ни условий акций.
    """
    lines = ["", "Предложение для клиента:"]
    if offer is not None:
        lines += offer.speech_lines()
        lines += [
            "Это всё, что ты знаешь о предложении. Ни других жилых комплексов, ни других цен, "
            "скидок, ставок и условий не называй, даже если клиент просит подробностей: скажи, "
            "что детали пришлёт коллега или обсудите на встрече.",
            "Подай предложение своими словами, к месту в разговоре, а не зачитывай списком.",
        ]
    else:
        lines += [
            "Конкретного предложения под этого клиента нет. Говори общими словами: подберём "
            "варианты "
            "под бюджет и район, покажем на встрече. Не называй ни жилых комплексов, ни цен, ни "
            "акций, "
            "ни ставок, ничего не выдумывай.",
        ]
    lines += [
        "Как покупают новостройку, когда своя квартира ещё не продана. Это общая механика рынка, "
        "её называть можно, но без цифр, без ставок и без привязки к конкретному дому. По порядку, "
        "от самого частого: ипотека, которую потом досрочно гасят деньгами от продажи, причём "
        "досрочное погашение идёт без штрафов и пеней; рассрочка от застройщика, но она обычно "
        "выходит дороже, потому что скидка за полную оплату при ней не действует, и об этом говори "
        "честно сам; у части застройщиков бывает короткая рассрочка на два-три месяца по цене "
        "полной "
        "оплаты, но это акция, а не общее правило. Конкретные суммы, ставки и условия по дому "
        "считает "
        "и называет специалист.",
    ]
    lines.append(
        "Если клиент назвал бюджет, комнатность или район, которых ты ещё не знал, "
        + _action(engine, "find_offer", "подбор предложения")
        + " и дальше говори только то, что он вернул. "
        "Если подбор ничего не вернул, переходи на общие слова."
    )
    return lines


